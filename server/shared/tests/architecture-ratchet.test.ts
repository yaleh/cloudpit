const TEST_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(TEST_DIR, '../../..');
const BASELINE_PATH = path.join(TEST_DIR, 'architecture-ratchet.baseline.json');

/** Repo-relative roots the criterion scans. `shared/` is the REPO-ROOT tree, not `server/shared/`. */
const SCAN_ROOTS = ['server', 'src', 'shared'] as const;
const PRUNED_DIRS = new Set(['node_modules', 'dist', 'tests']);
const OVERSIZE_LIMIT = 800;
const HOOK_HEAVY_THRESHOLD = 20;
const HELPER_NAMES = new Set(['isRecord', 'errorMessage', 'messageOf', 'describeError', 'expandHome']);
/** The provider directory that is ALLOWED to branch by provider name. */
const PROVIDER_LIST_DIR = 'server/modules/providers/list/';

const BASELINE_NOTE =
  'RATCHET: every reading in this file may only FALL. Lower a value (or remove an entry) when a ' +
  'refactor genuinely shrinks it; never raise one to accommodate a red. A legitimate RAISE must be ' +
  'recorded here in AC-394\'s "RECORDED CHANGE" format: a dated paragraph naming the file, the ' +
  'old→new reading and why the increase is the honest shape of the change. The criterion prints ' +
  '`ratchet: <dimension> <file> <baseline>→<measured>，可下调基线` whenever a reading falls; ' +
  'lowering the baseline is encouraged but not required, so a parallel refactor that shrinks a ' +
  'reading never reds this criterion.';

