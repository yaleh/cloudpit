function cloneReadings(readings: Readings): Readings {
  return {
    oversizeFiles: { ...readings.oversizeFiles },
    moduleMutableState: { ...readings.moduleMutableState },
    hookStateHeavy: { ...readings.hookStateHeavy },
    providerNameBranches: { ...readings.providerNameBranches },
    smallHelperCopies: { ...readings.smallHelperCopies },
  };
}

function firstKey(map: Record<string, number>): string {
  const [key] = Object.keys(map).sort();
  assert.ok(key, 'the baseline dimension must not be empty');
  return key;
}

function assertRed(baseline: Baseline, mutated: Readings, dimensionName: string, file: string): void {
  const { violations } = compare(mutated, baseline);
  console.log(`(AC3) ${dimensionName} red: ${violations.join(' | ')}`);
  assert.ok(violations.length > 0, `${dimensionName}: the mutated reading must red`);
  assert.ok(
    violations.some((violation) => violation.includes(dimensionName) && violation.includes(file)),
    `${dimensionName}: the red message must name the dimension and ${file} — got ${violations.join(' | ')}`,
  );
}

test('(AC3) each of the five dimensions reds on a +1 in-memory mutation, naming the dimension and file', () => {
  const baseline = readBaseline();
  const readings = measure(collectSources());
  const probe = 'server/modules/quay/__ratchet-probe.ts';

  // 1. one module-level `let` in a file outside the baseline
  const mutable = cloneReadings(readings);
  mutable.moduleMutableState[probe] = 1;
  assertRed(baseline, mutable, 'moduleMutableState', probe);

  // 2. one extra line on a file already in the oversize baseline
  const oversizeFile = firstKey(baseline.oversizeFiles);
  const bigger = cloneReadings(readings);
  bigger.oversizeFiles[oversizeFile] = baseline.oversizeFiles[oversizeFile] + 1;
  assertRed(baseline, bigger, 'oversizeFiles', oversizeFile);

  // 3. one provider-name branch in a file outside the baseline
  const providers = cloneReadings(readings);
  providers.providerNameBranches[probe] = 1;
  assertRed(baseline, providers, 'providerNameBranches', probe);

  // 4. a src file outside the baseline reaching the hook threshold
  const heavyFile = 'src/modules/quay/__ratchet-probe.tsx';
  const hooks = cloneReadings(readings);
  hooks.hookStateHeavy[heavyFile] = HOOK_HEAVY_THRESHOLD;
  assertRed(baseline, hooks, 'hookStateHeavy', heavyFile);

  // 5. one more `isRecord` declaration than the committed total
  const helpers = cloneReadings(readings);
  const shortfall = baseline.smallHelperCopies - totalHelperCopies(readings);
  helpers.smallHelperCopies[probe] = Math.max(1, shortfall + 1);
  assertRed(baseline, helpers, 'smallHelperCopies', probe);
});

