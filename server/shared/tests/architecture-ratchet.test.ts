/**
 * Architecture ratchet — five STRUCTURAL dimensions may only ever shrink.
 *
 * The repo already had a ratchet for import cycles (AC-394,
 * `server/shared/tests/server-import-cycle-budget.test.ts`). That one dimension is not enough:
 * after a refactor makes a 5000-line panel or a module-level mutable singleton smaller, nothing
 * stopped the next feature from growing it back. This criterion serialises the five readings the
 * architecture review kept finding by hand into one committed baseline and reds on the FIRST
 * commit that widens one of them.
 *
 * THE FIVE DIMENSIONS (each baseline entry is a file → reading):
 *
 *   1. `oversizeFiles`        non-test `.ts`/`.tsx` files over 800 lines → line count.
 *   2. `moduleMutableState`   module-level mutable state per file → count. A line that starts
 *                             `let ` (optionally `export let `), or a module-level
 *                             `const <id> = new Map|Set|WeakMap`, is one reading.
 *   3. `hookStateHeavy`       `src/` only: files with ≥ 20 `useState`/`useRef` CALLS → count.
 *                             A file not in the baseline must stay below 20.
 *   4. `providerNameBranches`  provider-name branches (`=== 'claude'` / `!== 'codex'` / …) per
 *                             file → count. `server/modules/providers/list/**` is exempt: that
 *                             directory is where per-provider code legitimately lives, and the
 *                             sibling task `gap-provider-capability-facets-replace-name-branches`
 *                             is what removes the branches elsewhere.
 *   5. `smallHelperCopies`    total declarations of `isRecord` / `errorMessage` / `messageOf` /
 *                             `describeError` / `expandHome` — a single integer. Function
 *                             DECLARATIONS only (`function <name>(…)`), not arrow aliases: that is
 *                             the shape the proposal counted (30 at立案 time).
 *
 * THE RATCHET: a reading may FALL freely (the criterion prints
 * `ratchet: <dimension> <file> <baseline>→<measured>，可下调基线`), but it may never RISE. A
 * baseline outside the committed entries is not grandfathered in: for `oversizeFiles` it may not
 * exceed 800 lines, and for the other three per-file dimensions it must be zero (or, for hooks,
 * below 20). Lowering the committed baseline is encouraged but NOT required — that is deliberate,
 * so a parallel refactor task that shrinks a reading never reds this criterion.
 *
 * THE BASELINE IS GENERATED BY THE SAME READING. `measure()` below is the only scanner;
 * `ARCHITECTURE_RATCHET_WRITE_BASELINE=1 npx tsx --tsconfig server/tsconfig.json --test
 * server/shared/tests/architecture-ratchet.test.ts` rewrites the committed JSON from it. There is
 * no second measurement implementation that could drift from the criterion.
 *
 * SCOPE: every non-test `.ts`/`.tsx` under `server/`, `src/` and the repo-root `shared/`.
 * `node_modules/`, `dist/` and `tests/` DIRECTORIES are pruned; `*.test.*`, `*.spec.*`, `*.d.ts`
 * and `__criterion-falsify-*` files are dropped by name (`__criterion-falsify-*` copies are
 * transient probes other criteria write and delete while this scan could be running).
 *
 * NOT INCLUDED: duplicate-code removable lines. `.archguard/` is excluded by
 * `.git/info/exclude`, so a task worktree cannot read it. When
 * `gap-architecture-refresh-duplicates-per-scope` makes `.archguard/query/duplicates/index.json`
 * trustworthy, that dimension can be added here — until then this criterion only PRINTS each
 * scope's `totalGroups` when the file happens to exist, and asserts nothing about it.
 */
