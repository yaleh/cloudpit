test('(duplicates) the archguard duplicate report, when readable, is printed but not asserted', () => {
  const duplicates = path.join(REPO_ROOT, '.archguard/query/duplicates/index.json');
  if (!fs.existsSync(duplicates)) {
    console.log('[architecture-ratchet] duplicates report absent (.archguard is excluded from task worktrees) — skipped');
    return;
  }
  const raw: unknown = JSON.parse(fs.readFileSync(duplicates, 'utf8'));
  assert.ok(typeof raw === 'object' && raw !== null, 'the duplicates index must be a JSON object');
  const record = raw as Record<string, unknown>;
  const scopes = record.scopes;
  if (typeof scopes !== 'object' || scopes === null) {
    console.log('[architecture-ratchet] duplicates report has no scopes object — nothing to print');
    return;
  }
  for (const [scope, value] of Object.entries(scopes as Record<string, unknown>)) {
    const totalGroups = typeof value === 'object' && value !== null ? (value as Record<string, unknown>).totalGroups : undefined;
    console.log(`[architecture-ratchet] duplicates scope=${scope} totalGroups=${String(totalGroups)}`);
  }
});
