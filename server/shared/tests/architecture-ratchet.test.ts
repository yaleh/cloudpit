/**
 * Every non-test `.ts`/`.tsx` under `<repoRoot>/{server,src,shared}`, paths relative to the repo
 * root (posix), sorted. Takes the root as an argument so the synthetic-fixture case drives the
 * same walk as the real tree.
 */
export function collectSources(repoRoot: string = REPO_ROOT): SourceFile[] {
  const files: SourceFile[] = [];
  const walk = (absDir: string): void => {
    for (const entry of fs.readdirSync(absDir, { withFileTypes: true })) {
      const abs = path.join(absDir, entry.name);
      if (entry.isDirectory()) {
        if (PRUNED_DIRS.has(entry.name)) continue;
        walk(abs);
        continue;
      }
      if (!entry.isFile()) continue;
      const name = entry.name;
      if (!name.endsWith('.ts') && !name.endsWith('.tsx')) continue;
      if (name.endsWith('.d.ts')) continue;
      if (name.includes('.test.') || name.includes('.spec.')) continue;
      if (name.startsWith('__criterion-falsify-')) continue;
      files.push({
        path: path.relative(repoRoot, abs).split(path.sep).join('/'),
        text: fs.readFileSync(abs, 'utf8'),
      });
    }
  };
  for (const root of SCAN_ROOTS) walk(path.join(repoRoot, root));
  return files.sort((a, b) => a.path.localeCompare(b.path));
}

// ---------------------------------------------------------------------------
// The readings — pure over the source set
// ---------------------------------------------------------------------------

function scriptKindFor(filePath: string): ts.ScriptKind {
  return filePath.endsWith('.tsx') ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
}

/** `wc -l` semantics: a trailing newline terminates the last line, it does not add one. */
function lineCount(text: string): number {
  return text.split('\n').length - (text.endsWith('\n') ? 1 : 0);
}

const MODULE_LET = /^(?:export\s+)?let\s/;
const MODULE_NEW_CONTAINER = /^(?:export\s+)?const\s+[A-Za-z_$][\w$]*.*=\s*new\s+(?:Map|Set|WeakMap)\b/;

/**
 * Module-level mutable state by the proposal's line-wise shape: a line that starts (column 0)
 * with `let `/`export let `, or a module-level `const <id> … = new Map|Set|WeakMap`.
 */
function moduleMutableState(text: string): number {
  let count = 0;
  for (const line of text.split('\n')) {
    if (MODULE_LET.test(line) || MODULE_NEW_CONTAINER.test(line)) count += 1;
  }
  return count;
}

/**
 * Provider-name branches: strict equality/inequality against one of the four provider literals.
 * The literal may be on the right (`provider === 'claude'`) or the left (`'claude' === provider`).
 */
function providerNameBranches(file: SourceFile): number {
  if (file.path.startsWith(PROVIDER_LIST_DIR)) return 0;
  const right = /(?:===|!==)\s*(['"])(?:claude|codex|cursor|opencode)\1/g;
  const left = /(['"])(?:claude|codex|cursor|opencode)\1\s*(?:===|!==)/g;
  return (file.text.match(right) ?? []).length + (file.text.match(left) ?? []).length;
}

type SyntaxCounts = { hookCalls: number; helperDeclarations: number };

/**
 * One syntax-tree pass per file, for the two readings that must not be fooled by text shape:
 * `useRef<HTMLDivElement>(null)` is a call whose callee is still `useRef`, and a generic
 * `function isRecord<T>(…)` is still a helper declaration.
 */
function countThroughSyntaxTree(file: SourceFile): SyntaxCounts {
  const sourceFile = ts.createSourceFile(file.path, file.text, ts.ScriptTarget.Latest, true, scriptKindFor(file.path));
  let hookCalls = 0;
  let helperDeclarations = 0;
  const visit = (node: ts.Node): void => {
    if (ts.isCallExpression(node) && ts.isIdentifier(node.expression)) {
      const name = node.expression.text;
      if (name === 'useState' || name === 'useRef') hookCalls += 1;
    } else if (ts.isFunctionDeclaration(node) && node.name && HELPER_NAMES.has(node.name.text)) {
      helperDeclarations += 1;
    }
    ts.forEachChild(node, visit);
  };
  visit(sourceFile);
  return { hookCalls, helperDeclarations };
}

/** The five dimensions over one source set. Deterministic: keys are inserted in sorted order. */
export function measure(sources: readonly SourceFile[]): Readings {
  const readings: Readings = {
    oversizeFiles: {},
    moduleMutableState: {},
    hookStateHeavy: {},
    providerNameBranches: {},
    smallHelperCopies: {},
  };

  for (const file of [...sources].sort((a, b) => a.path.localeCompare(b.path))) {
    const lines = lineCount(file.text);
    if (lines > OVERSIZE_LIMIT) readings.oversizeFiles[file.path] = lines;

    const mutable = moduleMutableState(file.text);
    if (mutable > 0) readings.moduleMutableState[file.path] = mutable;

    const branches = providerNameBranches(file);
    if (branches > 0) readings.providerNameBranches[file.path] = branches;

    const syntax = countThroughSyntaxTree(file);
    if (syntax.helperDeclarations > 0) readings.smallHelperCopies[file.path] = syntax.helperDeclarations;
    if (file.path.startsWith('src/') && syntax.hookCalls >= HOOK_HEAVY_THRESHOLD) {
      readings.hookStateHeavy[file.path] = syntax.hookCalls;
    }
  }

  return readings;
}

/** The single integer the baseline pins for dimension five. */
export function totalHelperCopies(readings: Readings): number {
  return Object.values(readings.smallHelperCopies).reduce((total, count) => total + count, 0);
}

