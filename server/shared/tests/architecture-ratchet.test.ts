/** A baseline document derived from a reading — this is what the write-baseline seam commits. */
export function baselineFrom(readings: Readings, measuredAt: string): Baseline {
  return {
    measuredAt,
    note: BASELINE_NOTE,
    oversizeFiles: { ...readings.oversizeFiles },
    moduleMutableState: { ...readings.moduleMutableState },
    hookStateHeavy: { ...readings.hookStateHeavy },
    providerNameBranches: { ...readings.providerNameBranches },
    smallHelperCopies: totalHelperCopies(readings),
  };
}

function readBaseline(): Baseline {
  const raw: unknown = JSON.parse(fs.readFileSync(BASELINE_PATH, 'utf8'));
  assert.ok(typeof raw === 'object' && raw !== null, 'the baseline must be a JSON object');
  const record = raw as Record<string, unknown>;
  const map = (key: string): Record<string, number> => {
    const value = record[key];
    assert.ok(typeof value === 'object' && value !== null && !Array.isArray(value), `baseline.${key} must be an object`);
    const out: Record<string, number> = {};
    for (const [file, count] of Object.entries(value as Record<string, unknown>)) {
      assert.ok(typeof count === 'number' && Number.isInteger(count) && count >= 0, `baseline.${key}.${file} must be a non-negative integer`);
      out[file] = count;
    }
    return out;
  };
  const measuredAt = record.measuredAt;
  assert.ok(typeof measuredAt === 'string' && /^\d{4}-\d{2}-\d{2}/.test(measuredAt), 'baseline.measuredAt must carry a date');
  const note = record.note;
  assert.ok(typeof note === 'string' && note.length > 0, 'baseline.note must be a non-empty string');
  const helperCopies = record.smallHelperCopies;
  assert.ok(typeof helperCopies === 'number' && Number.isInteger(helperCopies) && helperCopies >= 0, 'baseline.smallHelperCopies must be a non-negative integer');
  return {
    measuredAt,
    note,
    oversizeFiles: map('oversizeFiles'),
    moduleMutableState: map('moduleMutableState'),
    hookStateHeavy: map('hookStateHeavy'),
    providerNameBranches: map('providerNameBranches'),
    smallHelperCopies: helperCopies,
  };
}

/**
 * The ratchet comparison. A baseline entry may only fall; a file OUTSIDE the baseline must obey
 * the dimension's absolute floor (`> 800` for lines, `≥ 20` for hooks, `> 0` for the rest).
 * Returns the violations (red) and the "baseline can be lowered" hints (green).
 */
export function compare(readings: Readings, baseline: Baseline): Comparison {
  const violations: string[] = [];
  const notes: string[] = [];

  const dimension = (
    name: string,
    measured: Record<string, number>,
    pinned: Record<string, number>,
    isExternalViolation: (value: number) => boolean,
    rule: string,
  ): void => {
    const files = new Set([...Object.keys(pinned), ...Object.keys(measured)]);
    for (const file of [...files].sort()) {
      const now = measured[file] ?? 0;
      if (Object.prototype.hasOwnProperty.call(pinned, file)) {
        const was = pinned[file];
        if (now > was) {
          violations.push(`ratchet: ${name} ${file} ${was}→${now} — 基线内读数不得上调（此基线只允许下降）`);
        } else if (now < was) {
          notes.push(`ratchet: ${name} ${file} ${was}→${now}，可下调基线`);
        }
      } else if (isExternalViolation(now)) {
        violations.push(`ratchet: ${name} ${file} 基线外→${now} — ${rule}`);
      }
    }
  };

  dimension('oversizeFiles', readings.oversizeFiles, baseline.oversizeFiles, (value) => value > OVERSIZE_LIMIT, `基线外的文件不得超过 ${OVERSIZE_LIMIT} 行`);
  dimension('moduleMutableState', readings.moduleMutableState, baseline.moduleMutableState, (value) => value > 0, '基线外的文件模块级可变状态必须为 0');
  dimension('hookStateHeavy', readings.hookStateHeavy, baseline.hookStateHeavy, (value) => value >= HOOK_HEAVY_THRESHOLD, `基线外 src 文件的 hook 状态调用不得达到 ${HOOK_HEAVY_THRESHOLD}`);
  dimension('providerNameBranches', readings.providerNameBranches, baseline.providerNameBranches, (value) => value > 0, '基线外的文件不得新增 provider 名字分支');

  const helperTotal = totalHelperCopies(readings);
  if (helperTotal > baseline.smallHelperCopies) {
    const files = Object.keys(readings.smallHelperCopies).sort().join(', ');
    violations.push(
      `ratchet: smallHelperCopies <total> ${baseline.smallHelperCopies}→${helperTotal} — 小工具函数副本不得增加（files: ${files}）`,
    );
  } else if (helperTotal < baseline.smallHelperCopies) {
    notes.push(`ratchet: smallHelperCopies <total> ${baseline.smallHelperCopies}→${helperTotal}，可下调基线`);
  }

  return { violations, notes };
}

