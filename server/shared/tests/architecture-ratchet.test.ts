test('(AC4) a reading below the baseline is green and prints 可下调基线', () => {
  const readings = measure(collectSources());
  const baseline = readBaseline();
  const lowered: Baseline = {
    ...baseline,
    oversizeFiles: { ...baseline.oversizeFiles },
    moduleMutableState: { ...baseline.moduleMutableState },
    hookStateHeavy: { ...baseline.hookStateHeavy },
    providerNameBranches: { ...baseline.providerNameBranches },
    smallHelperCopies: baseline.smallHelperCopies + 1,
  };
  const oversizeFile = firstKey(lowered.oversizeFiles);
  lowered.oversizeFiles[oversizeFile] = lowered.oversizeFiles[oversizeFile] + 5;
  const mutableFile = firstKey(lowered.moduleMutableState);
  lowered.moduleMutableState[mutableFile] = lowered.moduleMutableState[mutableFile] + 1;

  const { violations, notes } = compare(readings, lowered);
  for (const note of notes) console.log(note);
  assert.deepEqual(violations, [], 'a reading below the baseline must stay green');
  assert.ok(notes.some((note) => note.includes('可下调基线')), 'a fallen reading must print the lowering hint');
  assert.ok(notes.some((note) => note.includes('oversizeFiles') && note.includes(oversizeFile)), 'the hint must name the fallen dimension and file');
});

